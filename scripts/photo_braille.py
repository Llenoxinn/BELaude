"""Turns the campus photos into Braille dot frames for the footer (src/components/campus.ts).

Each photo is cropped to the same grid and drawn as raised dots in two layers: outlines from an
edge filter, plus a Floyd-Steinberg fill of only the darkest tones (a full dither reads as noise).
The footer trades one frame for the next dot by dot.

Usage: python photo_braille.py out.ts [--preview]
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageFilter, ImageOps

COLS, ROWS = 120, 36  # character cells; 240 x 144 dots
EDGE_MIN = 100  # 0-255 edge strength that becomes a dot
TONE_GAMMA, TONE_MAX = 2.2, 70  # fill only pixels darker than TONE_MAX, after lifting mid-tones
W, H = COLS * 2, ROWS * 4
# Braille glyphs are 0.7em wide and set at line-height 1, so a dot is 1.4x wider than it is tall.
DOT_ASPECT = 0.7 / 2 / (1 / 4)
BASE = 0x2800
BIT = {(0, 0): 0, (0, 1): 1, (0, 2): 2, (1, 0): 3, (1, 1): 4, (1, 2): 5, (0, 3): 6, (1, 3): 7}

IMAGES = Path(__file__).resolve().parent.parent / 'src' / 'assets' / 'images'
# (file, export name, caption, crop focus x and y, 0..1)
PHOTOS = [
    ('up cebu with oble.jpg', 'OBLATION', 'The Oblation in front of the UP Cebu Administration Building', 0.5, 0.62),
    ('up cebu admin.jpeg', 'ADMIN', 'The UP Cebu Administration Building at dusk', 0.5, 0.72),
]


def crop(path, fx, fy):
    img = ImageOps.exif_transpose(Image.open(path)).convert('L')
    target = W * DOT_ASPECT / H
    w, h = img.size
    if w / h > target:
        cw = int(h * target)
        x0 = int((w - cw) * fx)
        img = img.crop((x0, 0, x0 + cw, h))
    else:
        ch = int(w / target)
        y0 = int((h - ch) * fy)
        img = img.crop((0, y0, w, y0 + ch))
    return ImageOps.autocontrast(img, cutoff=1)


def draw(path, fx, fy):
    img = crop(path, fx, fy)
    small = img.resize((W, H), Image.LANCZOS)
    # Edges at 3x then box-averaged down: steadier lines than filtering at dot size.
    big = img.resize((W * 3, H * 3), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1.2))
    edges = ImageOps.autocontrast(big.filter(ImageFilter.FIND_EDGES).resize((W, H), Image.BOX), cutoff=1)
    edges = ImageOps.expand(edges.crop((2, 2, W - 2, H - 2)), 2, 0)  # the filter rings the frame
    fill = dither(small.point(lambda v: int(255 * (v / 255) ** (1 / TONE_GAMMA))))
    return [[edges.getpixel((x, y)) > EDGE_MIN or (fill[y][x] and small.getpixel((x, y)) < TONE_MAX) for x in range(W)] for y in range(H)]


def dither(img):
    px = [[float(img.getpixel((x, y))) for x in range(W)] for y in range(H)]
    dots = [[False] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            old = px[y][x]
            new = 0.0 if old < 128 else 255.0
            dots[y][x] = new == 0.0
            err = old - new
            for dx, dy, k in ((1, 0, 7), (-1, 1, 3), (0, 1, 5), (1, 1, 1)):
                if 0 <= x + dx < W and y + dy < H:
                    px[y + dy][x + dx] += err * k / 16
    return dots


def encode(dots):
    out = []
    for r in range(0, H, 4):
        line = []
        for c in range(0, W, 2):
            code = 0
            for (x, y), b in BIT.items():
                if dots[r + y][c + x]:
                    code |= 1 << b
            line.append(chr(BASE + code))
        out.append(''.join(line))
    return out


def main():
    out = Path(sys.argv[1])
    parts = [
        '// Generated by scripts/photo_braille.py from the photos in src/assets/images. Do not edit by hand.',
        '',
        f'export const CAMPUS_SIZE = {{ cols: {COLS}, rows: {ROWS} }}',
        '',
        'export interface CampusFrame {\n  caption: string\n  lines: string[]\n}',
        '',
    ]
    names = []
    for file, name, caption, fx, fy in PHOTOS:
        lines = encode(draw(IMAGES / file, fx, fy))
        if '--preview' in sys.argv:
            print(name, '\n' + '\n'.join(lines), '\n')
        parts.append(f'const {name}: CampusFrame = ' + json.dumps({'caption': caption, 'lines': lines}, ensure_ascii=False, indent=2))
        parts.append('')
        names.append(name)
    parts.append(f'export const CAMPUS: CampusFrame[] = [{", ".join(names)}]')
    out.write_text('\n'.join(parts) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
